def test_divergent_covenant_versions_are_rejected(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    policy = license_policy.load_policy()
    contact = policy["commercial_contact"]
    copies = []
    for name, version in (("root.md", "2.0"), ("docs.md", "2.1")):
        path = tmp_path / name
        path.write_text(
            f"Report at {contact}.\n\nAdapted from the Contributor Covenant, version {version}.\n",
            encoding="utf-8",
        )
        copies.append(path)
    monkeypatch.setattr(license_policy, "CODE_OF_CONDUCT_COPIES", tuple(copies))
    errors = license_policy.validate_contributor_contract(policy)
    assert any("declare different Contributor Covenant versions: 2.0, 2.1" in e for e in errors)


def test_contributing_must_route_to_every_required_destination(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    contributing = tmp_path / "CONTRIBUTING.md"
    contributing.write_text("Run make pre-push.\n", encoding="utf-8")
    monkeypatch.setattr(license_policy, "CONTRIBUTING_PATH", contributing)
    errors = license_policy.validate_contributor_contract(license_policy.load_policy())
    assert set(license_policy.REQUIRED_CONTRIBUTOR_ROUTES) >= {
        "CLA.md",
        "CODE_OF_CONDUCT.md",
        "docs/legal/licensing.md",
        "SECURITY.md",
    }
    for required in license_policy.REQUIRED_CONTRIBUTOR_ROUTES:
        assert f"CONTRIBUTING.md does not route contributors to {required}" in errors


def test_checked_in_contributing_routes_every_required_destination() -> None:
    text = license_policy.CONTRIBUTING_PATH.read_text(encoding="utf-8")
    for required in license_policy.REQUIRED_CONTRIBUTOR_ROUTES:
        assert required in text


def test_obsolete_covenant_version_is_rejected(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    policy = license_policy.load_policy()
    contact = policy["commercial_contact"]
    copies = []
    for name in ("root.md", "docs.md"):
        path = tmp_path / name
        path.write_text(
            f"Report at {contact}.\n\nAdapted from the Contributor Covenant, version 2.0.\n",
            encoding="utf-8",
        )
        copies.append(path)
    monkeypatch.setattr(license_policy, "CODE_OF_CONDUCT_COPIES", tuple(copies))
    errors = license_policy.validate_contributor_contract(policy)
    # Coherent but obsolete: the divergence check alone would pass this.
    assert not any("declare different Contributor Covenant versions" in error for error in errors)
    assert sum("declares Contributor Covenant version 2.0" in error for error in errors) == 2


def test_checked_in_conduct_copies_adopt_the_required_covenant_version() -> None:
    for path in license_policy.CODE_OF_CONDUCT_COPIES:
        match = license_policy.COVENANT_VERSION_PATTERN.search(path.read_text(encoding="utf-8"))
        assert match is not None
        assert match.group(1) == license_policy.REQUIRED_COVENANT_VERSION


def test_report_records_the_canonical_repository_and_conduct_copies() -> None:
    report = license_policy.build_report(license_policy.load_policy(), [])
    assert report["canonical_repository"] == license_policy.CANONICAL_REPOSITORY
    assert "CODE_OF_CONDUCT.md" in report["code_of_conduct_copies"]
    assert "CLA.md" in report["current_docs"]
    assert license_policy.CANONICAL_REPOSITORY not in report["current_docs"]
